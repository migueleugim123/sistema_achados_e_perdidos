    private void jBCadastrarObjetoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBCadastrarObjetoActionPerformed
try {
    controller.setDescricao(jTDescricao.getText().trim());
    controller.setCategoria(jTCategoria.getText().trim());
    controller.setDataAchado(
            java.time.LocalDate.parse(jTDataAchado.getText().trim())
    );
    controller.setHoraAchado(
            java.time.LocalTime.parse(jTHoraAchado.getText().trim())
    );
    controller.setCampus(jTCampus.getText().trim());
    controller.setBloco(jTBloco.getText().trim());
    controller.setAmbiente(jTAmbiente.getText().trim());
    controller.setDetalhesSensiveis(
            jTDetalhesSensiveis.getText().trim()
    );

    controller.setDataLimiteGuarda(
            java.time.LocalDate.now().plusDays(90)
    );
    
    controller.setEmailUsuario(jTEmailUsuario.getText().trim());

    if (controller.cadastrarObjeto()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Objeto cadastrado com sucesso!"
        );
    }

} catch (java.time.format.DateTimeParseException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Confira a data (AAAA-MM-DD) e a hora (HH:MM ou HH:MM:SS)."
    );
} catch (IllegalArgumentException e) {
    javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao cadastrar objeto: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jBCadastrarObjetoActionPerformed

